    def change_site(self,index):
        self.gauge.setEnabled(index==2); self.gauge.setValue(1520 if index==0 else 750 if index==1 else 45); self.gauge_changed()
    def gauge_changed(self,*_):
        scale=self.gauge.value()/1520 if self.gauge.value()<300 else 1.
        self.canvas.distance=8*scale; self.canvas.target=np.array([0.,0.,.9])*scale; self.refresh()
    def safe(self,fn):
        try: fn()
        except Exception as exc: QMessageBox.warning(self,'Виртуальный стенд',str(exc))
    def toggle(self): self.running=not self.running; self.refresh()
    def reset(self):
        self.finish_session(); self.saved={}; self.store=None; self.running=False; self.position=1.8; self.t=0.; self.generation+=1; self.bench=SyntheticBench(); self.rows=[]; self.refresh()
    def tick(self):
        if not self.running: return
        self.t+=.05; self.position-=self.speed.value()*.05
        if self.position<-1.8: self.position=1.8; self.generation+=1; self.bench.associator.reset('virtual_GT')
        self.refresh(observe=True)
    def refresh(self,*args,observe=False):
        kind=KINDS[self.kind.currentText()]; light=self.light.value(); shutter=self.shutter.isChecked()
        if observe:
            image,events,telemetry=self.bench.step(kind,self.position,self.t,light,shutter,self.generation); self.rows.append(telemetry)
            for event in events:
                if self.saved.get(event['event_id'])!=event['observation_state']:
                    if self.store is None:
                        self.store=EventStore(OUT/'sessions'/datetime.now().strftime('%Y%m%d_%H%M%S_%f'))
                        save_json(self.store.root/'virtual_context.json',{'synthetic_GT_only':True,'model_inference':False,'not_camera_acceptance':True})
                    if self.store.submit(event,[(self.t,image)],{'synthetic_GT_only':True,'model_inference':False,'geometry_kind':kind,'display_sequence':self.bench.sequence,'clock_domain':'virtual_seconds_from_run_start','not_live_latency':True}): self.saved[event['event_id']]=event['observation_state']
        else:
            image,boxes,names,visible=synthetic_observation(kind,self.position,light,shutter); events=[]; telemetry={'assessed':light>=15 and not shutter}
        indicator='unassessed' if not telemetry['assessed'] else ('event' if self.saved else 'idle')
        self.canvas.meshes=scene('platform' if self.mode.currentIndex() else 'bench',kind,self.position,self.explode.value()/100,shutter,indicator,gauge_mm=self.gauge.value())
        self.canvas.brightness=.3+.7*light/100; self.canvas.caption=f'Колея {self.gauge.value():g} мм • t={self.t:.2f}с • концепция, не калибровка камеры'; self.canvas.update()
