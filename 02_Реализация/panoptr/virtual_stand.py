class StandCanvas(QWidget):
    def __init__(self,parent=None):
        super().__init__(parent); self.setMinimumSize(550,440); self.azimuth=35.; self.elevation=25.; self.distance=8.; self.target=np.array([0.,0.,.9]); self.meshes=[]; self.last=None; self.brightness=1.; self.caption=''
    def paintEvent(self,event):
        p=QPainter(self); p.setRenderHint(QPainter.Antialiasing); p.fillRect(self.rect(),QColor('#111e29'))
        a,e=math.radians(self.azimuth),math.radians(self.elevation)
        eye=self.target+self.distance*np.array([math.cos(e)*math.sin(a),math.cos(e)*math.cos(a),math.sin(e)])
        # Limit raster resolution on large screens; display resampling never claims sensor pixels.
        scale=min(1.,850/self.width()); width=max(1,int(self.width()*scale)); height=max(1,int(self.height()*scale))
        rgb=raster(self.meshes,eye,self.target,width,height,self.brightness)
        image=QImage(rgb.data,width,height,rgb.strides[0],QImage.Format_RGB888).copy(); p.drawImage(self.rect(),image)
        p.setPen(QColor('#dcecf4')); p.drawText(16,24,'3D • CPU • мышь: вращение • колесо: масштаб'); p.drawText(16,self.height()-16,self.caption)
    def mousePressEvent(self,e): self.last=e.position()
    def mouseMoveEvent(self,e):
        if self.last is not None and e.buttons()&Qt.LeftButton:
            d=e.position()-self.last; self.azimuth+=d.x()*.4; self.elevation=max(-5,min(80,self.elevation+d.y()*.3)); self.last=e.position(); self.update()
    def mouseReleaseEvent(self,e): self.last=None
    def wheelEvent(self,e): self.distance=max(.001,min(40,self.distance*math.exp(-e.angleDelta().y()/1000))); self.update()

def synthetic_observation(kind,y,light=100,shutter=False):
    """Orthographic fixture preview, not an image generated by the selected cameras."""
    image=np.full((480,800,3),(94,106,109),np.uint8)
    for x in (96,704):
        cv2.line(image,(x,0),(x,479),(163,175,181),14)
        for row in range(0,480,80): cv2.rectangle(image,(x-24,row),(x+24,row+13),(125,133,140),-1)
    visible=1.02<=y<=1.42; boxes=[]; names={0:kind}
    if visible:
        if kind in ('person','rock'): box=[340,180,460,310]
        else: box=[68,195,125,265]
        color={'person':(51,164,230),'rock':(92,105,120),'missing':(21,23,25),'inverted':(61,75,215),'normal':(142,153,161)}[kind]
        cv2.rectangle(image,tuple(box[:2]),tuple(box[2:]),color,-1)
        # Confidence 1 describes an exact geometric label; it is NOT model confidence.
        if kind!='normal': boxes=[box+[1.,0]]
    image=(image.astype(float)*max(0,min(100,light))/100).astype(np.uint8)
    if shutter: image[:]=0
    if shutter or light<15: boxes=[]
    return image,boxes,names,visible

class SyntheticBench:
    def __init__(self): self.associator=EventAssociator(); self.sequence=0; self.policy={'confirm_hits':2,'zone':[[.04,0],[.96,0],[.96,1],[.04,1]]}
    def step(self,kind,y,stamp,light=100,shutter=False,generation=1):
        image,boxes,names,visible=synthetic_observation(kind,y,light,shutter); self.sequence+=1
        health=frame_health(image,stamp,stamp,20,self.policy)
        if light<15:
            health['assessed']=False; health['reasons'].append('виртуальный свет ниже условного предела; не фотометрическая калибровка')
        updates=self.associator.update('virtual_GT',generation,self.sequence,stamp,boxes,names,image.shape,self.policy,health)
        return image,updates,{'time_s':stamp,'sequence':self.sequence,'kind':kind,'y_m':y,'visible':visible,'light_percent':light,
            'shutter':shutter,'assessed':health['assessed'],'synthetic_GT_only':True,'model_inference':False,'states':[e['observation_state'] for e in updates]}

def rehearsal(folder):
    folder=Path(folder); folder.mkdir(parents=True,exist_ok=True); rows=[]; summary=[]
    for kind,light,shutter in [('normal',100,False),('missing',100,False),('person',100,False),('rock',100,False),('missing',0,False),('person',100,True)]:
        b=SyntheticBench(); case=f'{kind}_{light}_{int(shutter)}'; store=EventStore(folder/case); saved={}; states=[]
        for i in range(31):
            t=i*.05; image,events,row=b.step(kind,1.45-.3*t,t,light,shutter); rows.append({'case':case,**row})
            for event in events:
                if saved.get(event['event_id'])!=event['observation_state']:
                    store.submit(event,[(t,image)],{'source':'virtual_orthographic_fixture','synthetic_GT_only':True,'model_inference':False,'scenario':case}); saved[event['event_id']]=event['observation_state']
                states.append(event['observation_state'])
        store.flush(); count=len(store.events()); store.close()
        cv2.imencode('.png',image)[1].tofile(str(folder/(case+'.png')))
        summary.append({'case':case,'event_cards':count,'observation_states':sorted(set(states)),
            'warning':'Tests event plumbing with synthetic GT. Not detection accuracy or railway acceptance.'})
    save_json(folder/'protocol.json',{'display_sampling_hz':20,'virtual_speed_m_s':.3,'rows':rows,'scenarios':summary,'GPU_used':False,'real_camera_used':False,'real_performance_verified':False})
    import csv
    with (folder/'protocol.csv').open('w',encoding='utf-8-sig',newline='') as f:
        writer=csv.DictWriter(f,fieldnames=list(rows[0])); writer.writeheader(); writer.writerows(rows)
    return summary

